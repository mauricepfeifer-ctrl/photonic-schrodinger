def _build_pricing_card(tier: dict, brand: dict) -> str:
    featured_class = " featured" if tier.get("featured") else ""
    featured_attr = f' data-featured-label="{tier.get("featured_label", "")}"' if tier.get("featured") else ""
    cta_class = "pricing-cta-primary" if tier.get("cta_style") == "primary" else "pricing-cta-secondary"
    paypal_url = build_paypal_url(brand["paypal_email"], tier["price"], tier["item_name"], brand.get("currency", "EUR"))

    features_html = "\n".join(f"<li>{f}</li>" for f in tier["features"])

    slug = tier["name"].lower().replace(" ", "")

    return f'''<div class="pricing-card{featured_class} fade-in"{featured_attr}>
    <div class="pricing-tier">{tier["tier_label"]}</div>
    <div class="pricing-name">{tier["name"]}</div>
    <div class="pricing-desc">{tier["description"]}</div>
    <div class="pricing-price">{format_price(tier["price"])} <span>{tier["price_suffix"]}</span></div>
    <div class="pricing-value">{tier["value_text"]}</div>
    <ul class="pricing-features">
        {features_html}
    </ul>
    <a href="{paypal_url}" class="pricing-cta {cta_class}" id="cta-{slug}">{tier["cta_text"]}</a>
</div>'''


def main():
    parser = argparse.ArgumentParser(description="🏗️ Landing Page Blueprint Generator")
    parser.add_argument("config", help="Path to JSON config file")
    parser.add_argument("--output", "-o", default="./output/", help="Output directory for generated index.html")
    args = parser.parse_args()

    cfg = load_config(args.config)
    html = generate_html(cfg)

    os.makedirs(args.output, exist_ok=True)
    output_path = os.path.join(args.output, "index.html")

