def _hex_to_rgb(hex_color: str) -> str:
    """Convert #f97316 to '249, 115, 22'."""
    h = hex_color.lstrip('#')
    return f"{int(h[0:2], 16)}, {int(h[2:4], 16)}, {int(h[4:6], 16)}"


