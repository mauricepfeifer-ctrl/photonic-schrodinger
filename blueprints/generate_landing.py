def load_config(path: str) -> dict:
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)


def format_price(price: int) -> str:
    """Format price with dot separator for thousands (German style)."""
    if price >= 1000:
        return f"€{price:,}".replace(",", ".")
    return f"€{price}"


def build_paypal_url(email: str, amount: int, item_name: str, currency: str = "EUR") -> str:
    return (
        f"https://www.paypal.com/cgi-bin/webscr?cmd=_xclick"
        f"&business={quote(email)}"
        f"&currency_code={currency}"
        f"&amount={amount}"
        f"&item_name={quote(item_name)}"
    )


